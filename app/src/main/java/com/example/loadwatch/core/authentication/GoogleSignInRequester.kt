package com.example.loadwatch.core.authentication

import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.example.loadwatch.R
import com.example.loadwatch.core.common.LogTags
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import javax.inject.Inject

sealed interface GoogleSignInResult {
    data class Success(val googleIdToken: String) : GoogleSignInResult

    // The user dismissed the account picker; not an error worth shouting about
    data object Cancelled : GoogleSignInResult

    // No Google account is available on the device
    data object NoGoogleAccount : GoogleSignInResult

    data object Failed : GoogleSignInResult
}

// Google sign-in through Credential Manager's Google ID token flow (not the deprecated GoogleSignIn client).
// The web client id is default_web_client_id, generated by the Google services plugin from google-services.json.
class GoogleSignInRequester @Inject constructor() {

    // activityContext must be an Activity: Credential Manager shows its account picker on top of it
    suspend fun requestGoogleIdToken(activityContext: Context): GoogleSignInResult {
        val option = GetSignInWithGoogleOption.Builder(activityContext.getString(R.string.default_web_client_id)).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()

        return try {
            val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
            if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                Log.i(LogTags.AUTH, "Received a Google ID token from Credential Manager")
                GoogleSignInResult.Success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                Log.w(LogTags.AUTH, "Credential Manager returned an unexpected credential type: ${credential.type}")
                GoogleSignInResult.Failed
            }
        } catch (e: GetCredentialCancellationException) {
            Log.i(LogTags.AUTH, "Google sign-in cancelled by the user")
            GoogleSignInResult.Cancelled
        } catch (e: NoCredentialException) {
            Log.w(LogTags.AUTH, "No Google account available for sign-in")
            GoogleSignInResult.NoGoogleAccount
        } catch (e: GetCredentialException) {
            Log.w(LogTags.AUTH, "Google sign-in failed: ${e.type}")
            GoogleSignInResult.Failed
        } catch (e: GoogleIdTokenParsingException) {
            Log.w(LogTags.AUTH, "Could not read the Google ID token credential")
            GoogleSignInResult.Failed
        }
    }
}
